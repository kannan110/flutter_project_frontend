// Mobile UI:  Transaction timeline cards — no fixed-width table columns.
// PDF:        HTML generated by Edge Function (v2 — print-quality A4 layout).
//             Saved to device as .html, openable in any browser, printable.
//
// Invoice tap: Tapping an invoice row navigates to InvoiceDetailScreen.
// Source:     ledger_entries only via get_retailer_statement() RPC.
// ─────────────────────────────────────────────────────────────────────────────

enum _Preset { today, last7, last30, thisMonth, lastMonth, custom }

extension _PresetLabel on _Preset {
  String get label => switch (this) {
    _Preset.today     => 'Today',
    _Preset.last7     => 'Last 7',
    _Preset.last30    => 'Last 30',
    _Preset.thisMonth => 'This Month',
    _Preset.lastMonth => 'Last Month',
    _Preset.custom    => 'Custom',
  };
}

class _TxConfig {
  final String   label;
  final IconData icon;
  final Color    iconBg;
  final Color    iconFg;
  const _TxConfig(this.label, this.icon, this.iconBg, this.iconFg);
}

_TxConfig _txConfig(String sourceType, String paymentMode) {
  final m = paymentMode.toUpperCase();
  switch (sourceType) {
    case 'invoice':
      return const _TxConfig('Invoice Sale',
          Icons.receipt_long_outlined,
          Color(0xFFFFF3E0), Color(0xFFE65100));
    case 'delivery':
      return _TxConfig('Cash at Delivery${m.isNotEmpty ? " ($m)" : ""}',
          Icons.local_shipping_outlined,
          const Color(0xFFE8F5E9), const Color(0xFF2E7D32));
    case 'payment':
      return _TxConfig('Payment Received${m.isNotEmpty ? " ($m)" : ""}',
          Icons.payments_outlined,
          const Color(0xFFE8F5E9), const Color(0xFF1B5E20));
    case 'credit_note':
      return const _TxConfig('Credit Note',
          Icons.discount_outlined,
          Color(0xFFF3E5F5), Color(0xFF6A1B9A));
    case 'opening_balance':
      return const _TxConfig('Opening Balance',
          Icons.account_balance_outlined,
          Color(0xFFE3F2FD), Color(0xFF0D47A1));
    default:
      return const _TxConfig('Adjustment',
          Icons.swap_horiz_outlined,
          Color(0xFFF5F5F5), Color(0xFF424242));
  }
}

// ─────────────────────────────────────────────────────────────────────────────
class RetailerStatementScreen extends ConsumerStatefulWidget {
  const RetailerStatementScreen({super.key, required this.retailerId});
  final String retailerId;

  @override
  ConsumerState<RetailerStatementScreen> createState() =>
      _RetailerStatementScreenState();
}

class _RetailerStatementScreenState
    extends ConsumerState<RetailerStatementScreen> {
  final _c = Supabase.instance.client;

  _Preset  _preset  = _Preset.last30;
  DateTime _from    = DateTime.now().subtract(const Duration(days: 29));
  DateTime _to      = DateTime.now();
  bool     _loading = false;
  bool     _pdfBusy = false;

  Map<String, dynamic> _data = {};

  // ── Derived ────────────────────────────────────────────────────────────────
  Map<String, dynamic> get _header =>
      (_data['header'] as Map?)?.cast<String, dynamic>() ?? {};
  double get _opening =>
      (_data['opening_balance'] as num?)?.toDouble() ?? 0;
  double get _closing =>
      (_data['closing_balance'] as num?)?.toDouble() ?? 0;
  Map<String, dynamic> get _summary =>
      (_data['summary'] as Map?)?.cast<String, dynamic>() ?? {};
  List<Map<String, dynamic>> get _rows =>
      List<Map<String, dynamic>>.from(
          (_data['rows'] as List?)
              ?.map((e) => (e as Map).cast<String, dynamic>()) ??
              []);

  @override
  void initState() {
    super.initState();
    _applyPreset(_Preset.last30);
  }

  // ── Preset ─────────────────────────────────────────────────────────────────
  void _applyPreset(_Preset p) {
    final now = DateTime.now();
    late DateTime from, to;
    switch (p) {
      case _Preset.today:
        from = to = now;
      case _Preset.last7:
        from = now.subtract(const Duration(days: 6)); to = now;
      case _Preset.last30:
        from = now.subtract(const Duration(days: 29)); to = now;
      case _Preset.thisMonth:
        from = DateTime(now.year, now.month, 1); to = now;
      case _Preset.lastMonth:
        from = DateTime(now.year, now.month - 1, 1);
        to   = DateTime(now.year, now.month, 0);
      case _Preset.custom:
        return;
    }
    setState(() { _preset = p; _from = from; _to = to; });
    _load();
  }

  Future<void> _pickCustomRange() async {
    final picked = await showDateRangePicker(
      context: context,
      initialDateRange: DateTimeRange(start: _from, end: _to),
      firstDate: DateTime(2024),
      lastDate: DateTime.now(),
      builder: (ctx, child) => Theme(
        data: Theme.of(ctx).copyWith(
            colorScheme: const ColorScheme.light(primary: kNavy)),
        child: child!,
      ),
    );
    if (picked == null || !mounted) return;
    setState(() {
      _preset = _Preset.custom;
      _from   = picked.start;
      _to     = picked.end;
    });
    _load();
  }

  // ── Load ───────────────────────────────────────────────────────────────────
  Future<void> _load() async {
    if (!mounted) return;
    setState(() { _loading = true; _data = {}; });
    try {
      final res = await _c.rpc('get_retailer_statement', params: {
        'p_retailer_id': widget.retailerId,
        'p_from_date':   DateFormat('yyyy-MM-dd').format(_from),
        'p_to_date':     DateFormat('yyyy-MM-dd').format(_to),
      }).timeout(const Duration(seconds: 15));
      if (mounted) setState(() {
        _data    = (res as Map?)?.cast<String, dynamic>() ?? {};
        _loading = false;
      });
    } catch (e) {
      if (mounted) {
        setState(() => _loading = false);
        _snack(e.toString().replaceAll('Exception: ', ''), error: true);
      }
    }
  }

  // ── PDF ────────────────────────────────────────────────────────────────────
  // Generates a genuine PDF directly from the already-loaded `_data` (the
  // same structured data the on-screen statement renders from) — no server
  // round-trip needed. This replaces the old "generate-retailer-statement-pdf"
  // Edge Function entirely: that function only ever produced base64-encoded
  // HTML (mimeType text/html), never a real PDF, regardless of its name.

  // Download — opens the native print/save preview with a real .pdf file
  Future<void> _download() async {
    if (_data.isEmpty) { _snack('Load statement first.', error: true); return; }
    setState(() => _pdfBusy = true);
    try {
      final company = ref.read(appUserProvider).valueOrNull?.companyName ?? 'DSR Chicken';
      final retailerName = _header['retailer_name'] as String? ?? 'Statement';
      await ReportPdfGenerator.generateRetailerStatementAndShow(
        context: context,
        data: _data,
        companyName: company,
        fromDate: _from,
        toDate: _to,
        retailerName: retailerName,
      );
    } catch (e) {
      if (mounted) _snack(e.toString().replaceAll('Exception: ', ''), error: true);
    } finally {
      if (mounted) setState(() => _pdfBusy = false);
    }
  }

  // Share — share sheet for WhatsApp, email, etc. — real .pdf bytes
  Future<void> _share() async {
    if (_data.isEmpty) { _snack('Load statement first.', error: true); return; }
    setState(() => _pdfBusy = true);
    try {
      final company = ref.read(appUserProvider).valueOrNull?.companyName ?? 'DSR Chicken';
      final retailerName = _header['retailer_name'] as String? ?? 'Statement';
      await ReportPdfGenerator.shareRetailerStatement(
        data: _data,
        companyName: company,
        fromDate: _from,
        toDate: _to,
        retailerName: retailerName,
      );
    } catch (e) {
      if (mounted) _snack(e.toString().replaceAll('Exception: ', ''), error: true);
    } finally {
      if (mounted) setState(() => _pdfBusy = false);
    }
  }

  // ── Navigation: invoice tap ────────────────────────────────────────────────
  void _openInvoice(String invoiceId) {
    context.push(R.invoiceDetailPath(invoiceId));
  }

  // ── Snackbar ───────────────────────────────────────────────────────────────
  void _snack(String msg, {bool error = false}) {
    if (!mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(SnackBar(
      content: Text(msg),
      backgroundColor: error ? Colors.red.shade700 : Colors.green.shade700,
    ));
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // BUILD
  // ═══════════════════════════════════════════════════════════════════════════
  @override
  Widget build(BuildContext context) => Scaffold(
    backgroundColor: kBgPage,
    appBar: _appBar(),
    body: Column(children: [
      _presetBar(),
      Expanded(child: _body()),
    ]),
  );

  // ── AppBar ─────────────────────────────────────────────────────────────────
  PreferredSizeWidget _appBar() {
    final name = _header['retailer_name'] as String? ?? 'Statement';
    return AppBar(
      backgroundColor: kNavy,
      foregroundColor: Colors.white,
      elevation: 0,
      leading: IconButton(
        icon: const Icon(Icons.arrow_back),
        onPressed: () => context.canPop() ? context.pop() : null,
      ),
      title: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        mainAxisSize: MainAxisSize.min,
        children: [
          Text(name,
              style: const TextStyle(fontSize: 14, fontWeight: FontWeight.w800,
                  color: Colors.white),
              overflow: TextOverflow.ellipsis),
          const Text('Account Statement',
              style: TextStyle(fontSize: 11, color: Color(0xFFB4C6F4))),
        ],
      ),
      actions: [
        if (_pdfBusy)
          const Padding(
            padding: EdgeInsets.symmetric(horizontal: 14),
            child: SizedBox(width: 20, height: 20,
                child: CircularProgressIndicator(
                    strokeWidth: 2, color: Colors.white)),
          )
        else ...[
          // Download icon
          IconButton(
            icon: const Icon(Icons.download_outlined),
            tooltip: 'Download Statement',
            onPressed: _download,
          ),
          // Share icon
          IconButton(
            icon: const Icon(Icons.share_outlined),
            tooltip: 'Share Statement',
            onPressed: _share,
          ),
        ],
        IconButton(
          icon: const Icon(Icons.refresh_rounded),
          onPressed: _loading ? null : _load,
        ),
      ],
    );
  }

  // ── Preset bar ─────────────────────────────────────────────────────────────
  Widget _presetBar() => Container(
    color: kSurface,
    padding: const EdgeInsets.fromLTRB(12, 8, 8, 8),
    child: Row(children: [
      Expanded(
        child: SingleChildScrollView(
          scrollDirection: Axis.horizontal,
          child: Row(
            children: _Preset.values.map((p) {
              final sel = _preset == p;
              return Padding(
                padding: const EdgeInsets.only(right: 6),
                child: GestureDetector(
                  onTap: () => p == _Preset.custom
                      ? _pickCustomRange() : _applyPreset(p),
                  child: AnimatedContainer(
                    duration: const Duration(milliseconds: 150),
                    padding: const EdgeInsets.symmetric(
                        horizontal: 12, vertical: 6),
                    decoration: BoxDecoration(
                      color: sel ? kNavy : kBgPage,
                      borderRadius: BorderRadius.circular(20),
                      border: Border.all(color: sel ? kNavy : kBorderLight),
                    ),
                    child: Text(p.label,
                        style: TextStyle(
                            fontSize: 11, fontWeight: FontWeight.w700,
                            color: sel ? Colors.white : kTextSub)),
                  ),
                ),
              );
            }).toList(),
          ),
        ),
      ),
      const SizedBox(width: 4),
      Text(
        '${DateFormat('d MMM').format(_from)}–${DateFormat('d MMM').format(_to)}',
        style: const TextStyle(fontSize: 10, color: kTextHint),
        overflow: TextOverflow.ellipsis,
      ),
    ]),
  );

  // ── Body ───────────────────────────────────────────────────────────────────
  Widget _body() {
    if (_loading) {
      return const Center(
          child: CircularProgressIndicator(color: kNavy, strokeWidth: 2));
    }
    if (_data.isEmpty) {
      return Center(
        child: Column(mainAxisSize: MainAxisSize.min, children: [
          Icon(Icons.receipt_long_outlined, size: 56,
              color: kTextHint.withValues(alpha: 0.4)),
          const SizedBox(height: 12),
          const Text('Select a date range to load statement',
              style: TextStyle(color: kTextHint, fontSize: 13)),
        ]),
      );
    }
    return RefreshIndicator(
      onRefresh: _load,
      color: kNavy,
      child: ListView(
        padding: const EdgeInsets.fromLTRB(12, 12, 12, 100),
        children: [
          _heroCard(),
          const SizedBox(height: 12),
          _summaryGrid(),
          const SizedBox(height: 16),
          _sectionLabel('TRANSACTIONS'),
          const SizedBox(height: 8),
          _openingTile(),
          ..._rows.map(_transactionTile),
          _closingTile(),
          const SizedBox(height: 20),
          _actionButtons(),
        ],
      ),
    );
  }

