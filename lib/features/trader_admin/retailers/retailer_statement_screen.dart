  // ── Summary grid ───────────────────────────────────────────────────────────
  Widget _summaryGrid() {
    final invoiced  = (_summary['total_invoiced']    as num?)?.toDouble() ?? 0;
    final collected = (_summary['total_collections'] as num?)?.toDouble() ?? 0;
    final cash      = (_summary['cash_collected']    as num?)?.toDouble() ?? 0;
    final upi       = (_summary['upi_collected']     as num?)?.toDouble() ?? 0;
    final bank      = (_summary['bank_collected']    as num?)?.toDouble() ?? 0;
    final credits   = (_summary['total_credit_notes']as num?)?.toDouble() ?? 0;

    return Column(children: [
      Row(children: [
        Expanded(child: _kpiTile('Total Sales', Fmt.amount(invoiced),
            Icons.trending_up_rounded, const Color(0xFFE65100))),
        const SizedBox(width: 8),
        Expanded(child: _kpiTile('Collected', Fmt.amount(collected),
            Icons.payments_outlined, const Color(0xFF2E7D32))),
      ]),
      const SizedBox(height: 8),
      Row(children: [
