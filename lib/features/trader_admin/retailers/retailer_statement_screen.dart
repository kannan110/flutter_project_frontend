  // ── Transaction tile ───────────────────────────────────────────────────────
  Widget _transactionTile(Map<String, dynamic> row) {
    final sourceType = row['source_type'] as String? ?? '';
    final payMode    = row['payment_mode'] as String? ?? '';
    final isDebit    = row['entry_type'] == 'debit';
    final amount     = (row['amount']          as num?)?.toDouble() ?? 0;
    final balance    = (row['running_balance'] as num?)?.toDouble() ?? 0;
    final refNo      = row['ref_number']  as String?;
    final invoiceId  = row['invoice_id']  as String?;  // ← navigation target
    final dateStr    = row['entry_date']  as String? ?? '';
    final date       = DateTime.tryParse(dateStr);
    final cfg        = _txConfig(sourceType, payMode);

    final parts = <String>[];
    final birds = row['birds']       as num?;
    final wt    = row['weight_kg']   as num?;
    final rate  = row['rate_per_kg'] as num?;
    if (birds != null) parts.add('${birds.toInt()} birds');
    if (wt    != null) parts.add('${wt.toStringAsFixed(2)} kg');
    if (rate  != null) parts.add('₹${rate.toStringAsFixed(0)}/kg');

    return _tile(
      date:      date ?? DateTime.now(),
      icon:      cfg.icon, iconBg: cfg.iconBg, iconFg: cfg.iconFg,
      label:     cfg.label, refNo: refNo,
      metaText:  parts.isEmpty ? null : parts.join(' · '),
      isDebit: isDebit, amount: amount, balance: balance,
      isFirst: false, isLast: false,
      // Invoice rows are tappable
      onTap: (sourceType == 'invoice' && invoiceId != null)
          ? () => _openInvoice(invoiceId) : null,
      tappable: sourceType == 'invoice' && invoiceId != null,
    );
  }

  // ── Core timeline tile ─────────────────────────────────────────────────────
  Widget _tile({
    required DateTime date,
    required IconData icon,
    required Color    iconBg,
    required Color    iconFg,
    required String   label,
    required String?  refNo,
    required String?  metaText,
    required bool     isDebit,
    required double   amount,
    required double   balance,
    required bool     isFirst,
    required bool     isLast,
    bool highlighted  = false,
    VoidCallback? onTap,
    bool tappable     = false,
  }) {
    final amtColor = isDebit ? Colors.red.shade700 : Colors.green.shade700;
    final balColor = balance > 0 ? Colors.red.shade700 : Colors.green.shade700;

    return IntrinsicHeight(
      child: Row(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
        // Timeline column
        // NOTE: IntrinsicHeight forbids double.infinity children.
        // Use Expanded for both line segments so the Column fills by flex.
        SizedBox(width: 40, child: Column(mainAxisSize: MainAxisSize.max, children: [
          // Top line segment (hidden for first tile)
          Expanded(child: Center(child: Container(
            width: 2,
            color: isFirst ? Colors.transparent : kBorderLight,
          ))),
          // Icon dot
          Container(width: 32, height: 32,
            decoration: BoxDecoration(
              color: iconBg, shape: BoxShape.circle,
              border: highlighted ? Border.all(color: iconFg, width: 2) : null,
            ),
            child: Icon(icon, size: 15, color: iconFg),
          ),
          // Bottom line segment (hidden for last tile)
          Expanded(child: Center(child: Container(
            width: 2,
            color: isLast ? Colors.transparent : kBorderLight,
          ))),
        ])),
        const SizedBox(width: 8),

        // Card
        Expanded(child: GestureDetector(
          onTap: onTap,
          child: Container(
            margin: const EdgeInsets.only(bottom: 8),
            padding: const EdgeInsets.all(12),
            decoration: BoxDecoration(
              color: highlighted
                  ? (balance > 0
                  ? const Color(0xFFFFF3F3) : const Color(0xFFF1FFF5))
                  : kSurface,
              borderRadius: BorderRadius.circular(12),
              border: Border.all(
                color: tappable
                    ? const Color(0xFFE65100).withValues(alpha: 0.35)
                    : highlighted
                    ? (balance > 0
                    ? Colors.red.shade200 : Colors.green.shade200)
                    : kBorderLight,
              ),
            ),
            child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
              // Label + amount
              Row(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Expanded(child: Row(children: [
                  Expanded(child: Text(label,
                      style: TextStyle(
                          fontSize: 13,
                          fontWeight: highlighted
                              ? FontWeight.w900 : FontWeight.w700,
                          color: kTextMain))),
                  // "View Invoice" badge for invoice rows
                  if (tappable) ...[
                    const SizedBox(width: 4),
                    Container(
                      padding: const EdgeInsets.symmetric(
                          horizontal: 6, vertical: 2),
                      decoration: BoxDecoration(
                        color: const Color(0xFFE65100).withValues(alpha: 0.1),
                        borderRadius: BorderRadius.circular(4),
                      ),
                      child: Row(mainAxisSize: MainAxisSize.min, children: [
                        const Icon(Icons.open_in_new_rounded, size: 10,
                            color: Color(0xFFE65100)),
                        const SizedBox(width: 3),
                        const Text('View', style: TextStyle(
                            fontSize: 9, fontWeight: FontWeight.w700,
                            color: Color(0xFFE65100))),
                      ]),
                    ),
                  ],
                ])),
                const SizedBox(width: 8),
                ConstrainedBox(
                  constraints: const BoxConstraints(minWidth: 70),
                  child: Text(
                    '${isDebit ? "+" : "−"} ${Fmt.amount(amount)}',
                    style: TextStyle(fontSize: 13, fontWeight: FontWeight.w800,
                        color: amtColor),
                    textAlign: TextAlign.right,
                    overflow: TextOverflow.ellipsis,
                  ),
                ),
              ]),

              // Date + ref + meta
              const SizedBox(height: 4),
              Wrap(spacing: 8, runSpacing: 2, children: [
                Text(DateFormat('d MMM yyyy').format(date),
                    style: const TextStyle(fontSize: 10, color: kTextHint)),
                if (refNo != null && refNo.isNotEmpty)
                  Container(
                    padding: const EdgeInsets.symmetric(
                        horizontal: 6, vertical: 1),
                    decoration: BoxDecoration(
                      color: kBorderLight.withValues(alpha: 0.6),
                      borderRadius: BorderRadius.circular(4),
                    ),
                    child: Text(refNo, style: const TextStyle(
                        fontSize: 10, color: kTextSub,
                        fontWeight: FontWeight.w600)),
                  ),
                if (metaText != null)
                  Text(metaText, style: const TextStyle(
                      fontSize: 10, color: kTextHint)),
              ]),

              // Running balance
              const SizedBox(height: 6),
              Row(children: [
                const Text('Balance: ',
                    style: TextStyle(fontSize: 10, color: kTextHint)),
                Text(Fmt.amount(balance),
                    style: TextStyle(fontSize: 11, fontWeight: FontWeight.w800,
                        color: balColor),
                    overflow: TextOverflow.ellipsis),
                const Spacer(),
                Text(balance > 0 ? 'payable' : 'credit',
                    style: TextStyle(fontSize: 9, color: balColor)),
              ]),
            ]),
          ),
        )),
      ]),
    );
  }

